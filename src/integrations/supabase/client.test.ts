import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

const createClient = vi.fn(() => ({}));
vi.mock("@supabase/supabase-js", () => ({ createClient }));
// The host the page is served on: a firm's address, or (null) the bare domain.
let hostAddress: string | null = null;
vi.mock("@/lib/firmHost", () => ({ firmAddressFromHost: () => hostAddress }));

const SUPABASE = "https://project.supabase.example";

type Options = { auth?: { detectSessionInUrl?: boolean }; global?: { fetch?: typeof fetch } };

/** The client as client.ts makes it for a page served at a host naming `address`, and what it hands supabase-js. */
async function clientAt(address: string | null): Promise<Options> {
  hostAddress = address;
  vi.resetModules();
  createClient.mockClear();
  await import("./client");
  expect(createClient).toHaveBeenCalledTimes(1);
  return (createClient.mock.calls[0] as unknown[])[2] as Options;
}

/** The headers a request through the client's fetch reached the network with. */
async function sentHeaders(options: Options, input: string | Request, init?: RequestInit): Promise<Headers> {
  const network = vi.fn(async () => new Response("[]"));
  vi.stubGlobal("fetch", network);
  expect(options.global?.fetch).toBeTypeOf("function");
  await options.global!.fetch!(input, init);
  const call = network.mock.calls[0] as unknown as [RequestInfo | URL, RequestInit | undefined];
  return new Headers(call[1]?.headers ?? (call[0] instanceof Request ? call[0].headers : undefined));
}

beforeEach(() => {
  vi.stubEnv("VITE_SUPABASE_URL", SUPABASE);
});

afterEach(() => {
  vi.unstubAllGlobals();
  vi.unstubAllEnvs();
});

describe("the Supabase client", () => {
  it("never signs this browser in from tokens in the address", async () => {
    // With detection on, any page load whose address carries #access_token=…&refresh_token=… replaces the
    // session this browser holds, so a link someone sends could sign the reader into the sender's account
    // (a guest's intake lost, and what they type next going to the sender). Email links carry a 6-digit code
    // or a #token_hash the callback page verifies on a click (docs/SUPABASE_SETUP.md), never a session.
    // client.ts is regenerated by Lovable: this test fails if a regeneration drops the setting.
    const options = await clientAt(null);
    expect(options.auth?.detectSessionInUrl).toBe(false);
  });

  describe("the firm address (CRM-S1.1b, D-40)", () => {
    // At a firm's address every request to the database names that address, and the database answers for that firm only
    // (supabase/migrations/20261117090000_one_firm_at_a_time.sql). Without it a member of two firms sees both mixed together.
    // client.ts is regenerated by Lovable: these fail if a regeneration drops the header.
    it("names the firm's address on every request to the database, keeping the request's own headers", async () => {
      const options = await clientAt("alpha-advisory");
      const headers = await sentHeaders(options, `${SUPABASE}/rest/v1/rpc/my_firms`, {
        method: "POST",
        headers: { Authorization: "Bearer t", apikey: "k" },
      });
      expect(headers.get("x-firm-address")).toBe("alpha-advisory");
      expect(headers.get("authorization")).toBe("Bearer t");
      expect(headers.get("apikey")).toBe("k");
    });

    it("also on a request handed over as a Request object", async () => {
      const options = await clientAt("alpha-advisory");
      const headers = await sentHeaders(options, new Request(`${SUPABASE}/rest/v1/chamber_sessions?select=id`, { headers: { apikey: "k" } }));
      expect(headers.get("x-firm-address")).toBe("alpha-advisory");
      expect(headers.get("apikey")).toBe("k");
    });

    it("sends no address on the bare domain, so the database answers as it always has", async () => {
      const options = await clientAt(null);
      const headers = await sentHeaders(options, `${SUPABASE}/rest/v1/rpc/my_firms`, { method: "POST" });
      expect(headers.has("x-firm-address")).toBe(false);
    });

    it("sends it to the database only: sign-in, files and server functions don't read it, and a server function would refuse it", async () => {
      // A server function's CORS rule lists the headers it accepts; an unlisted one fails the browser's preflight.
      const options = await clientAt("alpha-advisory");
      for (const path of ["/auth/v1/token?grant_type=password", "/functions/v1/invite-member", "/storage/v1/object/sign/documents/x"]) {
        const headers = await sentHeaders(options, `${SUPABASE}${path}`, { method: "POST" });
        expect(headers.has("x-firm-address")).toBe(false);
      }
      const elsewhere = await sentHeaders(options, "https://elsewhere.example/rest/v1/x");
      expect(elsewhere.has("x-firm-address")).toBe(false);
    });
  });
});
